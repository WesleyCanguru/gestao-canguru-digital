Este é o jeito da casa de montar estratégia de Google Ads e Meta Ads. Vale para todo cliente. O cadastro diz o que o cliente acha; o Raio-X diz o que existe de verdade. Quando os dois discordam, o Raio-X vence, e a diferença vira pergunta para o cliente.

## 1. Antes de escrever qualquer coisa
- Leia o Raio-X inteiro: tags instaladas (inclusive dentro do Google Tag Manager e do lado do servidor), páginas do site, contatos, Instagram e velocidade.
- Nunca mande "instalar" algo que o Raio-X mostra instalado. Se há 2 pixels, 2 contêineres ou 2 Analytics, o trabalho é unificar, e antes disso descobrir quem configurou e de qual conta é cada um. Se há rastreamento do lado do servidor, alguém fez um trabalho avançado: não remova nada sem falar com essa pessoa.
- Nunca mande criar uma página que o sitemap mostra que existe. Use as páginas existentes como destino (modelo, preço, comparação, agendamento, contato).
- Use a data de hoje que vem nos dados. Diga em que época do ano estamos para esse negócio (alta ou baixa temporada, datas e eventos do setor).

## 2. O público vem primeiro
Uma estratégia boa começa por quem compra, não por quem gosta. Para cada cliente, responda:
- **Quem compra de verdade?** Idade, momento de vida, renda e patrimônio compatíveis com o ticket, o que já tem hoje (por exemplo, já é dono de um produto menor e quer subir de nível), onde mora, onde passa o tempo.
- **Quem decide junto?** Em compras de família (casa, barco, carro, escola, saúde), o cônjuge pesa. Não restrinja gênero quando a decisão é dividida.
- **Quem não é público?** Curiosos, quem procura aluguel, usado, emprego, peça, grátis. Afaste esse público com o criativo (preço visível, linguagem do comprador), com o formulário (perguntas que filtram) e com as negativas do Google.
- **Existe um nicho com vantagem injusta?** Comunidade que já conhece a marca, idioma, região, profissão. Exemplo: marca brasileira nos EUA fala com brasileiros e latinos em português e espanhol.
- **Onde o cliente pode atender?** A região do anúncio precisa caber na logística real (onde o cliente vê o produto, onde o serviço chega, quem atende em que idioma).

Monte de 3 a 6 públicos, cada um com nome, por que compra, como segmentar e qual criativo fala com ele:
1. Intenção (Google): quem já pesquisa o produto, a categoria, a marca ou o concorrente.
2. Comprador mais provável (Meta).
3. Decisor ou co-decisor, quando houver.
4. Nicho com vantagem, quando houver.
5. Remarketing por temperatura: quente (até 30 dias: viu preço, comparação, agendamento, abriu o formulário, clicou no WhatsApp) e morno (até 180 dias: viu 50% ou mais de um vídeo, visitou o site, interagiu com o perfil). Exclua quem já é lead ou cliente.
6. Semelhantes à lista de clientes, só com 100 contatos ou mais.

Regras do Meta: interesse é sinal para o Advantage+, não um filtro fechado. Nos EUA o Meta não segmenta por renda e quase não segmenta por cargo: o filtro de renda vem do preço no anúncio, da região (CEPs e cidades de alta renda) e do formulário. Anúncios de crédito, emprego e moradia (categorias especiais) não podem segmentar por idade, gênero ou CEP: avise quando o cliente cair nisso.

## 3. Estrutura e verba
- Cada campanha precisa de pelo menos US$ 10 por dia (ou R$ 40 por dia no Brasil) para sair da fase de aprendizado. Número de campanhas = verba diária ÷ esse mínimo, arredondado para baixo. Na dúvida, menos campanhas e mais grupos dentro delas.
- Com verba de até US$ 1.500 (ou R$ 5.000) por mês, o normal são 2 a 3 campanhas.
- Google primeiro quando existe gente procurando o produto. Meta para criar demanda e para remarketing.
- Ticket alto e ciclo longo (acima de US$ 20 mil ou R$ 50 mil, ou decisão de semanas): no Meta frio, vídeo ou engajamento para formar público barato; o lead vem no remarketing, com formulário de maior intenção. Ticket baixo e decisão rápida (serviço local, consulta): formulário ou WhatsApp direto no frio é aceitável.
- Serviço local nos EUA: considere Local Services Ads e buscas com "near me" e urgência.
- Marca do cliente no Google: grupo próprio, barato, protege o nome.
- Concorrentes como palavra-chave só com o OK do cliente e nunca citando a marca de terceiros no texto do anúncio.

## 4. Ticket, ciclo e conversão certa
- A conversão que importa é a que antecede a venda: reunião, visita, test drive, sea trial, orçamento com dados completos. Clique no WhatsApp não é venda.
- Em ticket alto, mostre o preço de partida no anúncio quando ele for público: filtra curiosos e qualifica quem fica.
- Formulário com 3 a 5 perguntas que separam comprador de curioso (prazo de compra, situação atual, forma de pagamento, região).
- O lead precisa de dono: quem atende, em quanto tempo, em que idioma. Sem isso, nenhuma campanha funciona.

## 5. Google Ads
- Uma campanha de pesquisa com grupos por intenção (marca, produto ou modelo com preço, categoria, idioma). Negativas desde o primeiro dia.
- Região: "pessoas na região ou que estão com frequência nela", nunca "interessadas na região".
- Destino: a página mais específica que existe (modelo, preço, serviço). Home só para marca.
- Lance: maximizar conversões contando só as conversões principais.

## 6. Rastreamento (semana 1, sempre)
- Liste no plano os IDs reais que o Raio-X achou e diga o que fazer com cada um.
- Conversões contadas uma vez só: formulário, agendamento, ligação, WhatsApp.
- Meta: um pixel por conta, com a API de Conversões. Google: tag do Ads ligada ao Analytics e ao Search Console.
- Mês 2: devolver as etapas do CRM (qualificado, visita, venda) ao Google e ao Meta como conversões offline. É isso que ensina as plataformas a buscar comprador.

## 7. Criativos
- Comece pelo material que o cliente já tem. Peça material novo só onde faz falta.
- Vídeo: o produto em uso nos 3 primeiros segundos, vertical para Reels e Stories.
- Um ângulo por público (o que move cada um), e a prova certa (garantia, certificação, tempo de mercado, depoimento).
- Idioma da comunidade quando houver nicho com idioma.
- Anúncios saem da página do próprio cliente, nunca de página de fábrica, de matriz ou de perfil pessoal.

## 8. Expectativas e métricas
- Prometa processo, não resultado: rastreamento certo na semana 1, campanhas no ar na semana 2, custo por lead real na semana 4.
- Custo por lead e volume entram como faixa de referência, a confirmar depois de 4 semanas.
- Não prometa venda em baixa temporada nem em ciclo longo dentro do primeiro mês.
- Inclua uma métrica de qualidade (taxa de lead qualificado lida no CRM).

## 9. Regras de setor
- Advocacia no Brasil: Provimento 205/2021 da OAB (sem promessa de resultado, sem captação, sem preço de causa).
- Saúde no Brasil: regras dos conselhos (CFM, CFO, CRN): sem antes e depois sensacionalista, sem promessa de cura.
- Meta: categorias especiais (crédito, emprego, moradia) limitam a segmentação.
- Marcas de terceiros: sem citação negativa nem comparação enganosa.

## 10. Escrita
- Frases curtas, sem jargão, sem travessão (—). "Para", nunca "pra". O cliente lê.
- Dúvida da agência vai em pontos_em_aberto, que o cliente não vê. A primeira dúvida é sempre a que muda a estratégia (região, atendimento, verba).

